def closedloop_rows(G):
    """Closed-loop readings shared by Table V and the forest plot of make_fig_closedloop_v1.py (not in the paper): whole-call difference and 90% interval from the registry, difference after 30 s from closedloop-steady-qoe-v1, SSIM (ours minus reference) and freezes from each batch's valid runs. Returns group headers as ("group", text) and data rows as dicts with label, indent, D, ci, after, ssim, fz, st and unit."""
    import statistics as stt
    S = json.loads((R / "closedloop_steady_qoe_v1/summary.json").read_text())
    def arm_stat(b, arm, k):
        rows = [json.loads(l) for l in open(R / b.replace("-", "_") / "runs_full.jsonl")]
        xs = [r[k] for r in rows if r.get("valid") and r["arm"] == arm and isinstance(r.get(k), (int, float))]
        return stt.mean(xs) if xs else None
    def row(label, m, st, indent=False, unit="VMAF", **kw): return dict(label=label, indent=indent, D=m["D"], ci=tuple(m["ci90"]), st=st, unit=unit, **{"after": None, "ssim": None, "fz": None, **kw})
    def ss_fz(b):
        return dict(ssim=arm_stat(b, 'arm_ch_x', 'ssim') - arm_stat(b, 'gcc_pt125_c200', 'ssim'),
                    fz=(arm_stat(b, 'arm_ch_x', 'file_freeze_per_min'), arm_stat(b, 'gcc_pt125_c200', 'file_freeze_per_min')))
    def gcc_row(label, b, st, indent=False):
        full = S[b]["vmaf"] if b == "hd720-echo-attr-ch-v1" else G[b][-1]
        assert abs(full["D"] - S[b]["vmaf"]["D"]) < 1e-9, b
        return row(label, full, st, indent, after=S[b]["steady"]["D"], **ss_fz(b))
    rts = json.loads((R / "closedloop_steady_qoe_v1/realtrace_explore_v1.json").read_text())["steady"]
    def c320_rows():
        c3 = json.loads((R / "content320_ch_gcc_v1/result_v1.json").read_text()); out = []
        for k, lab, ind in (("low", "320x240 Johnny", False), ("medium", "Mobcal", True), ("high", "Parkrun", True)):
            v = c3[k]; m = {a: sum(x['ssim'] for x in v['by_arm_cap'][a].values()) / 3 for a in ("dep", "gcc")}
            out.append(row(lab, v["vmaf_diff"], "--", ind, ssim=m["dep"] - m["gcc"]))
        return out
    rt = G["hd720-realtrace-ch-v1"][-1]; lb = G["hd720-learned-baselines-v1"][-1]; lbr = json.loads((R / "hd720_learned_baselines_v1/result_v1.json").read_text())["ch_vs_mlp"]
    la = json.loads((R / "hd720_learned_alone_v1/result_rejudge_env0.json").read_text()); he = G["hd720-hb-learned-env-v1"][-1]; ha = G["hd720-hb-learned-alone-v1"][-1]
    le = G["lowbw-ch-vs-conf-env6-v1"][-1]; lf = G["lowbw-chf-vs-conf-v1"][-1]; l2 = G["lowbw-loss200-ch-v1"][-1]; cf = G["compete-flow-ch-v1"][-1]; l1 = G["lowbw-loss1-env6-v1"][-1]
    return [("group", "Python GCC every 200 ms (VMAF)"),
            gcc_row("720p, first batch", "hd720-closedloop-ch-v1", "R"),
            gcc_row("second batch", "hd720-echo-attr-ch-v1", "--", True),
            gcc_row("seeds 0 and 2", "hd720-seeds-ch-v1", "R", True),
            row("cellular, 7 windows", rt, "P", True, after=rts["D"], **ss_fz("hd720-realtrace-ch-v1")),
            gcc_row("High bandwidth", "hd720-highbw-ch-v1", "R"),
            gcc_row("Random loss", "hd720-randloss-ch-v1", "R"),
            row("Shared link (share, pp)", {"D": 100 * cf["S"], "ci90": [100 * x for x in cf["ci90"]]}, "D", unit="share"),
            *c320_rows(),
            ("group", "Learned estimators (VMAF)"),
            row("Schaferct-R", lb, "R"),
            row("high bandwidth", he, "R", True),
            row("Supervised MLP", lbr, "--"),
            row("Schaferct-R, no envelope", la, "P"),
            row("high bandwidth", ha, "D", True),
            ("group", "LLM4Band, 100 to 400 kb/s, 320x240 (utility)"),
            row("Behind the envelope", le, "R", unit="utility"),
            row("1% loss", l1, "R", True, unit="utility"),
            row("Estimators alone", lf, "R", unit="utility"),
            row("200 kb/s, 1% loss", l2, "N", True, unit="utility")]


