def tnotes(text):
    """Table notes below the table (threeparttable, 8 pt, normal case), following IEEE style: a one-line title above, explanations and lettered footnotes below."""
    return [r"\begin{tablenotes}[para,flushleft]\footnotesize", text, r"\end{tablenotes}"]


def reg():
    """Map each experiment id to the metrics of its data events in registry order; callers take the latest with [-1]."""
    d = {}
    for l in open(ROOT / "experiments/registry.jsonl"):
        e = json.loads(l)
        if e.get("event") == "data" and e.get("metrics"): d.setdefault(e["id"], []).append(e["metrics"])
    return d


