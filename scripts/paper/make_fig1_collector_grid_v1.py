#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""The 15 x 10 grid inside the collector box of Fig. 1: the 15 features over five 60 ms and five 600 ms windows that the
collector hands to the estimator at one step, drawn from a real observation rather than as decoration.
Data: one run of hd720-closedloop-v1 (2 Mb/s, Johnny, first run); the first decision step at least 60 s after
shaping starts (150 values, index 10 x feature + window; windows 0 to 4 are 60 ms, 5 to 9 are 600 ms).
Each row is normalised by its largest absolute value (an all-zero row takes the lightest colour); cells are separated by
0.012 cm white gaps, with a 0.1 cm gap between the 60 ms and 600 ms halves. --palette picks the colour ramp and
--lighten moves every channel towards white by that fraction. The paper uses --palette greys --lighten 0.4.
Usage: python3 scripts/paper/make_fig1_collector_grid_v1.py --palette greys --lighten 0.4 --out papers/revision-v2/figs/src/collector_grid_greys_light.tex
"""
import argparse, gzip, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = Path("/path/to/testbed/results/hd720-closedloop-v1/main/hd_c2__johnny__pp__r1/obs_arm_llm4bandpp_x__hd_c2__d0__r1__vjohnny.jsonl.gz")
OUT = ROOT / "papers/revision-v2/figs/src/collector_grid.tex"
CW, RH, GAP, SEP, LO = 0.16, 0.065, 0.1, 0.012, 0.06
CX, Y0 = 8.85, 2.06
X0 = CX - (10 * CW + GAP) / 2


def colour(t, palette):
    """Return the 0-255 RGB colour for t in [0, 1] on the chosen ramp."""
    if palette == "blues":
        import matplotlib
        c = matplotlib.colormaps["Blues"](0.12 + 0.73 * t); return tuple(round(255 * v) for v in c[:3])
    lo, hi = {"indigo": ((0xEC, 0xEE, 0xFB), (0x3F, 0x4C, 0xA8)), "greys": ((0xEE, 0xEE, 0xEE), (0x3A, 0x3A, 0x3A))}[palette]
    return tuple(round(a + (b - a) * t) for a, b in zip(lo, hi))


def main():
    global A
    ap = argparse.ArgumentParser(); ap.add_argument("--palette", default="blues", choices=["blues", "indigo", "greys"]); ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--lighten", type=float, default=0.0)
    A = ap.parse_args()
    rows = [json.loads(l) for l in gzip.open(SRC, "rt")]
    t0 = rows[0]["t_ms"]; r = next(x for x in rows if (x["t_ms"] - t0) / 1000.0 >= 60.0); o = r["obs"]
    assert len(o) == 150
    L = [f"% Generated by scripts/paper/make_fig1_collector_grid_v1.py --palette {A.palette} --lighten {A.lighten}; do not edit. Data: the observation {(r['t_ms'] - t0) / 1000.0:.2f} s after shaping starts in {SRC.name}."]
    for f in range(15):
        row = [abs(float(o[10 * f + w])) for w in range(10)]; m = max(row)
        for w in range(10):
            v = (row[w] / m) if m > 0 else 0.0
            rgb = colour(LO + (1 - LO) * v if m > 0 else 0.0, A.palette)
            rgb = tuple(round(255 - (255 - c) * (1 - A.lighten)) for c in rgb)
            x = X0 + CW * w + (GAP if w > 4 else 0.0); y = Y0 - RH * f
            L.append(f"\\fill[fill={{rgb,255:red,{rgb[0]};green,{rgb[1]};blue,{rgb[2]}}}] ({x + SEP / 2:.4f},{y - SEP / 2:.4f}) rectangle ({x + CW - SEP / 2:.4f},{y - RH + SEP / 2:.4f});")
    Path(A.out).write_text("\n".join(L) + "\n"); print("Written", A.out, "cell count", 150, "palette", A.palette)


if __name__ == "__main__":
    main()
