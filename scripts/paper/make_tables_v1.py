def shade_min_per_column(table, cols):
    """Return the (row, column) cells that hold the minimum of each column in cols; ties are all marked."""
    marks = set()
    for c in cols:
        vals = [r[c] for r in table]
        lo = min(vals)
        marks |= {(i, c) for i, v in enumerate(vals) if abs(v - lo) < 1e-12}
    return marks


