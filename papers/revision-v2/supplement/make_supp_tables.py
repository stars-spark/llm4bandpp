#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build the supplement tables and the prompt listing from result files and the experiment registry; no number is typed by hand.
Writes to generated/ next to this script:
  tab_eplus.tex         Table S4: e+ and e- of every Table I row on the 870 validation calls (main-table-unified-v1, offline-trivial-baselines-v1, deployed estimator seed 1)
  tab_variants.tex      Table S3: per-scenario MSE of the fifteen-token variants with a capacity anchor, mean of three seeds, macro checked against the registry
  tab_ablation_old.tex  written only when the earlier manuscript's LaTeX source is present (not in this package); the supplement does not use it
  tab_designer_src.tex  Table S5: balanced accuracy per client stack (realtel-scale-v1, realtel-scale-namehide-v1, open-model outputs rescored)
  prompt_template.txt   Fig. S2: the frozen designer prompt, taken from scripts/coldstart/realtel_adapter_v1.py by AST and checked against its hash
Usage: python3 make_supp_tables.py
"""
import ast, hashlib, json, re, sys
sys.dont_write_bytecode = True
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
R = ROOT / "experiments/results"
REG = ROOT / "experiments/registry.jsonl"
OUT = HERE / "generated"
OUT.mkdir(exist_ok=True)
SC = ["Low BW", "High BW", "Fluctuating"]


def registry(i):
    return [e for e in map(json.loads, open(REG, encoding="utf-8")) if e.get("id") == i]


def write(name, lines):
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Written", name)


def tab_eplus():
    r = json.loads((R / "main_table_unified_v1/result.json").read_text())["rows"]
    rows = dict(r); rows.update(json.loads((R / "offline_trivial_baselines_v1/result.json").read_text())["rows"])
    dt = [k for k in rows if "Decision Transformer" in k and "p90" in k]; assert len(dt) == 1
    nl = json.loads((R / "nl_2x2_v1/eval/CHs1.json").read_text())["summaries"]
    rows["NL_deployed"] = {"870": {c: {"e_plus": nl[c]["over"], "e_minus": nl[c]["under"]} for c in SC}}
    rl = ["Pioneer", "Schaferct(public)", "Schaferct(retrained)", dt[0], "LLM4Band conference version online weights (Qwen)", "LLM4band++ (Qwen)", "NL_deployed"]
    ref = ["MLP_seed0", "ReceiveRateEcho"]
    name = {"Pioneer": "Pioneer", "Schaferct(public)": "Challenge baseline", "Schaferct(retrained)": "Schaferct-R", dt[0]: r"Decision Transf.$^{a}$",
            "LLM4Band conference version online weights (Qwen)": "LLM4Band (Qwen)", "LLM4band++ (Qwen)": r"LLM variant, 1 tok.$^{b}$", "NL_deployed": r"LLM4band++, deployed$^{c}$",
            "MLP_seed0": r"Supervised MLP$^{d}$", "ReceiveRateEcho": r"Rec.-rate echo$^{e}$"}
    assert abs(rows["LLM4band++ (Qwen)"]["870"]["macro_mse"] - 6.743) < 5e-4 and abs(rows["Pioneer"]["870"]["macro_mse"] - 7.368) < 5e-4
    L = [r"% Generated by supplement/make_supp_tables.py from the result.json of main-table-unified-v1 and offline-trivial-baselines-v1; rows as in Table I of the main text. Edit the script, not this file.",
         r"\begin{tabular}{@{}l@{\hspace{4pt}}cc@{\hspace{6pt}}cc@{\hspace{6pt}}cc@{}}", r"\toprule",
         r"& \multicolumn{2}{c}{Low BW} & \multicolumn{2}{c}{High BW} & \multicolumn{2}{c}{Fluctuating} \\ \cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(l){6-7}",
         r"Estimator & $e^{+}$ & $e^{-}$ & $e^{+}$ & $e^{-}$ & $e^{+}$ & $e^{-}$ \\", r"\midrule"]
    for grp in (rl, ref):
        for k in grp:
            v = []
            for c in SC:
                v += [rows[k]["870"][c]["e_plus"], rows[k]["870"][c]["e_minus"]]
            L.append(f"{name[k]} & " + " & ".join(f"{x:.3f}" for x in v) + r" \\")
        if grp is rl:
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("tab_eplus.tex", L)


def seeds(d, tag):
    out = []
    for s in (0, 1, 2):
        j = json.loads((d / f"{tag}s{s}_50000.json").read_text())
        out.append(j["summaries"])
    return out


def mean_arm(S):
    m = {c: {k: sum(x[c][k] for x in S) / len(S) for k in ("mse", "over", "under")} for c in SC}
    per_seed_macro = [sum(x[c]["mse"] for c in SC) / 3 for x in S]
    macro = sum(m[c]["mse"] for c in SC) / 3
    macro_over = sum(m[c]["over"] for c in SC) / 3
    return m, macro, macro_over, per_seed_macro


def tab_variants():
    arms = [
        ("Pre-trained, LoRA", R / "llm_indispensability/paper_data/raw", "LLM", 5.803129081385389),
        ("Pre-trained, full", R / "pretrained_fulltrain_fourth_arm/raw", "PF", 5.779211181839429),
        ("Random init., full", R / "pretrained_fulltrain_fourth_arm/raw", "RI", 5.653009156400839),
        ("No LLM", R / "llm_indispensability/paper_data/raw", "NL", 5.797209626619039),
        ("No LLM, Mamba agg.", R / "aggregator_mamba_control_v1", "MB", 5.674067166680071),
    ]
    reg = {"LLM": registry("llm-indispensability-mt-anchor-3seed"), "PF": registry("llm-pretraining-fulltrain-fourth-arm-3seed"),
           "MB": registry("aggregator-mamba-control-v1")}
    dm = next(e for e in reg["LLM"] if e["event"] == "data")["metrics"]
    assert abs(dm["mean_macro_candidate"] - arms[0][3]) < 1e-9 and abs(dm["mean_macro_reference"] - arms[3][3]) < 1e-9
    df = next(e for e in reg["PF"] if e["event"] == "data")["metrics"]
    assert abs(df["mean_macro_pf"] - arms[1][3]) < 1e-9 and abs(df["mean_macro_randinit"] - arms[2][3]) < 1e-9
    dmb = next(e for e in reg["MB"] if e["event"] == "data" and e["metrics"])["metrics"]
    assert abs(dmb["macro_mse_mamba"] - arms[4][3]) < 1e-9
    L = [r"% Generated by supplement/make_supp_tables.py: per-seed evaluation files (step 50000, 870 calls) averaged over seeds; macro means match the registry to within 1e-6. Edit the script, not this file.",
         r"% Sources: llm-indispensability-mt-anchor-3seed (LoRA arm with the LLM and the arm without it), llm-pretraining-value-randinit-fair-3seed and llm-pretraining-fulltrain-fourth-arm-3seed (randomly initialized and pre-trained full arms), aggregator-mamba-control-v1 (Mamba aggregator); the deployed row from main-table-unified-v1.",
         r"\begin{tabular}{@{}l@{\hspace{4pt}}ccc@{\hspace{5pt}}c@{\hspace{5pt}}c@{\hspace{5pt}}c@{}}", r"\toprule",
         r"Arm (15 tokens, anchor) & Low & High & Fluct. & Macro & Seeds & Macro $e^{+}$ \\", r"\midrule"]
    for nm, d, tag, ref in arms:
        m, macro, mo, ps = mean_arm(seeds(d, tag))
        assert abs(macro - ref) < 1e-6, (nm, macro, ref)
        L.append(f"{nm} & " + " & ".join(f"{m[c]['mse']:.2f}" for c in SC) + f" & {macro:.3f} & {min(ps):.2f}--{max(ps):.2f} & {mo:.3f}" + r" \\")
    r = json.loads((R / "main_table_unified_v1/result.json").read_text())["rows"]["LLM4band++ (Qwen)"]["870"]
    mo = sum(r[c]["e_plus"] for c in SC) / 3
    L += [r"\midrule",
          r"LLM variant, 1 token$^{a}$ & " + " & ".join(f"{r[c]['mse']:.2f}" for c in SC) + f" & {r['macro_mse']:.3f} & -- & {mo:.3f}" + r" \\",
          r"\bottomrule", r"\end{tabular}"]
    write("tab_variants.tex", L)


def tab_ablation_old():
    src = (ROOT / "papers/rejected-tmm/content/5-experiment-1.tex").read_text(encoding="utf-8")
    blk = src[src.index(r"\label{tab:ablation}"):src.index(r"\end{tabular}", src.index(r"\label{tab:ablation}"))]
    want = [("LLM4Band", "Conference encoder, base reward"), ("+ HCQ", "Conference encoder, HCQ"),
            ("+ MS-ENC", "Our encoder, base reward"), (r"\textbf{Full (++)}", "Our encoder, HCQ")]
    L = [r"% Parsed by supplement/make_supp_tables.py from tab:ablation in papers/rejected-tmm/content/5-experiment-1.tex (read only); the last column, the mean over the three scenarios, is computed by the script. Edit the script, not this file.",
         r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
         r"Row of the earlier table & Low & High & Fluct. & Printed & Mean \\", r"\midrule"]
    for key, label in want:
        line = next(l for l in blk.splitlines() if l.strip().startswith(key + " &") or l.strip().startswith(key + "&"))
        # Ten numbers per row: MSE, e+ and e- for High, Low and Fluctuating, then the printed average MSE.
        nums = [float(x) for x in re.findall(r"(?<![\w.])\d+\.\d+", re.sub(r"\\cellcolor\{[^}]*\}", "", line))]
        assert len(nums) == 10, (key, nums)
        hi, lo, fl, printed = nums[0], nums[3], nums[6], nums[9]
        L.append(f"{label} & {lo:.3f} & {hi:.3f} & {fl:.3f} & {printed:.3f} & {(hi + lo + fl) / 3:.3f}" + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("tab_ablation_old.tex", L)


# Balanced accuracy as in realtel_adapter_v1.ba: mean of the mappable and unmappable halves; an empty half counts as 1.
def ba(rows):
    s = [x for r in rows for x in r["same"]]; n = [x for r in rows for x in r["none"]]
    return 0.5 * (sum(s) / len(s) if s else 1.0) + 0.5 * (sum(n) / len(n) if n else 1.0)


def tab_designer_src():
    sys.path.insert(0, str(ROOT / "scripts/coldstart"))
    import realtel_adapter_v1 as M
    import realtel_scale_v1 as RS
    assert M.ba is not None
    D = R / "realtel_scale_v1"
    J = json.loads((D / "judge.json").read_text())
    H = json.loads((D / "namehide/judge.json").read_text())
    S = RS.load_sources()
    assert abs(ba(J["rows_llm"]) - J["ba_llm"]) < 1e-12 and abs(ba(H["rows"]) - H["ba_llm"]) < 1e-12
    assert abs(ba(J["rows_base"]["CUPID"]) - J["ba_base"]["CUPID"]) < 1e-12
    opn = {}
    for tag in ("r1_32b", "r1_14b"):
        L = {}
        for j in map(json.loads, open(D / f"out_open_{tag}.jsonl")):
            _, n, k = j["id"].split("|")
            try: L[(n, int(k))] = M.parse(j["text"], len(S[n]["fields"]))
            except Exception: L[(n, int(k))] = None
        for n in S:
            for k in range(M.NPRES): L.setdefault((n, k), None)
        opn[tag] = RS.rows(S, L)
    assert abs(ba(opn["r1_32b"]) - 0.893) < 5e-4 and abs(ba(opn["r1_14b"]) - 0.693) < 5e-4
    short = {"Agora Web SDK": "Agora Web SDK", "Twilio Video JS": "Twilio Video", "Daily (daily-js)": "Daily", "Jitsi (lib-jitsi-meet)": "lib-jitsi-meet",
             "mediasoup v3": "mediasoup", "Pion WebRTC": "Pion", "Janus WebRTC Server": "Janus", "LiveKit protocol": "LiveKit",
             "SRT": "SRT", "ns-3 FlowMonitor": "ns-3 FlowMonitor", "Microsoft Teams CQD": "Teams CQD", "Chrome legacy getStats (goog)": "Chrome legacy"}
    sel = lambda rows, n: [r for r in rows if r["source"] == n]
    L = [r"% Generated by supplement/make_supp_tables.py from judge.json of realtel-scale-v1 (hosted model with real names, and Cupid), namehide/judge.json (realtel-scale-namehide-v1), "
         r"and out_open_r1_32b.jsonl and out_open_r1_14b.jsonl (reported only, rescored with the scoring of realtel_scale_v1); per-source balanced accuracy as in the main table. Edit the script, not this file.",
         r"\begin{tabular}{@{}l@{\hspace{3pt}}c@{\hspace{5pt}}cc@{\hspace{5pt}}cc@{\hspace{5pt}}c@{}}", r"\toprule",
         r"& Scored & \multicolumn{2}{c}{Hosted} & \multicolumn{2}{c}{Open} & \\ \cmidrule(lr){3-4}\cmidrule(lr){5-6}",
         r"Client stack & map/none & names & masked & 32B & 14B & Cupid \\", r"\midrule"]
    for n in S:
        t = S[n]["truth"]; ns = sum(x[0] == "same" for x in t); nn = sum(x[0] == "none" for x in t)
        if ns + nn == 0:
            continue
        cells = [ba(sel(J["rows_llm"], n)), ba(sel(H["rows"], n)), ba(sel(opn["r1_32b"], n)), ba(sel(opn["r1_14b"], n)), ba(sel(J["rows_base"]["CUPID"], n))]
        L.append(f"{short[n]} & {ns}/{nn} & " + " & ".join(f"{x:.2f}" for x in cells) + r" \\")
    tot = [J["ba_llm"], H["ba_llm"], ba(opn["r1_32b"]), ba(opn["r1_14b"]), J["ba_base"]["CUPID"]]
    nsum = sum(sum(x[0] == "same" for x in S[n]["truth"]) for n in S); nnone = sum(sum(x[0] == "none" for x in S[n]["truth"]) for n in S)
    L += [r"\midrule", f"All 11 & {nsum}/{nnone} & " + " & ".join(f"{x:.3f}" for x in tot) + r" \\", r"\bottomrule", r"\end{tabular}"]
    write("tab_designer_src.tex", L)


def prompt_template():
    src = (ROOT / "scripts/coldstart/realtel_adapter_v1.py").read_text(encoding="utf-8")
    tree = ast.parse(src); val = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) and node.targets[0].id in ("TEMPLATE", "FEAT"):
            val[node.targets[0].id] = ast.literal_eval(node.value)
    T, F = val["TEMPLATE"], val["FEAT"]
    h = hashlib.sha256((T + json.dumps(F)).encode()).hexdigest()
    assert h.startswith("d2467ef5dc35"), h
    spec = "\n".join(f"{i}. {s}" for i, s in enumerate(F))
    txt = T.format(spec=spec, header="<SOURCE DESCRIPTION>",
                   fields="<ONE LINE PER FIELD: field j: name | object | defining text>")
    (OUT / "prompt_template.txt").write_text(txt + "\n", encoding="utf-8")
    assert all(ord(c) < 128 for c in txt), "prompt contains non-ASCII characters, listings need separate handling"
    print("Written prompt_template.txt, template hash", h[:12])


if __name__ == "__main__":
    tab_eplus(); tab_variants(); tab_designer_src(); prompt_template()
    if (ROOT / "papers/rejected-tmm/content/5-experiment-1.tex").is_file(): tab_ablation_old()
